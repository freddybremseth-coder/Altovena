import assert from 'node:assert/strict';
import {transition} from '../lib/nexus-task-policy.mjs';
const base={id:'task-demo',brandId:'altovena',status:'review_required',proposedBy:'agent-1',qualityReviewed:true,evidence:[{type:'source',ref:'example'}],version:2,actionType:'publish',actionDigest:'sha256:example-v2'};
const reviewer={id:'reviewer-1',brandIds:['altovena'],permissions:['task:approve']};
const executor={id:'executor-1',brandIds:['altovena'],permissions:['task:execute']};
const date='2026-10-15T19:00:00Z';
const approve=transition({task:base,actor:reviewer,next:'approved',now:date});
assert.equal(approve.to,'approved');
const denied=(task,actor,next,approval,code)=>assert.throws(()=>transition({task,actor,next,approval,now:date}),{message:code});
denied(base,{...reviewer,id:'agent-1'},'approved',undefined,'SEPARATION_OF_DUTIES');
denied(base,{...reviewer,brandIds:['other']},'approved',undefined,'BRAND_SCOPE_DENIED');
denied({...base,evidence:[]},reviewer,'approved',undefined,'EVIDENCE_REQUIRED');
denied({...base,status:'completed'},reviewer,'approved',undefined,'TRANSITION_DENIED');
denied({...base,status:'approved'},executor,'executing',undefined,'VALID_APPROVAL_REQUIRED');
denied({...base,status:'approved'},executor,'executing',{taskId:'task-demo',brandId:'altovena',actorId:'reviewer-1',decision:'approved',version:1},'VALID_APPROVAL_REQUIRED');
const validApproval={taskId:'task-demo',brandId:'altovena',actorId:'reviewer-1',decision:'approved',version:2,actionType:'publish',actionDigest:'sha256:example-v2',expiresAt:'2026-10-16T19:00:00Z'};
denied({...base,status:'approved'},executor,'executing',{...validApproval,actionDigest:'tampered'},'ACTION_CHANGED');
denied({...base,status:'approved'},executor,'executing',{...validApproval,expiresAt:'2026-10-15T18:00:00Z'},'APPROVAL_EXPIRED');
denied({...base,status:'approved'},executor,'executing',{...validApproval,actionType:'send_email'},'VALID_APPROVAL_REQUIRED');
denied({...base,status:'approved'},executor,'executing',{...validApproval,actorId:'executor-1'},'VALID_APPROVAL_REQUIRED');
denied({...base,status:'approved',actionType:'read_only'},executor,'executing',undefined,'VALID_APPROVAL_REQUIRED');
const run=transition({task:{...base,status:'approved'},actor:executor,next:'executing',approval:validApproval,now:date});
assert.equal(run.to,'executing');
assert.ok(Object.isFrozen(run));
console.log('PASS: Nexus task policy rejects invalid approvals, stale versions, wrong brand and unauthorized transitions.');
